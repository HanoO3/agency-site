/**
 * Helper to fetch a project by its slug (supports aliases)
 */
export function getProjectBySlug(slug: string): Project | undefined {
  const normalized = slug.toLowerCase();
  return projects.find(
    (p) =>
      p.slug.toLowerCase() === normalized ||
      (normalized === "magicbox" && p.slug === "magicbox-mglink") ||
      (normalized === "igbioscience" && p.slug === "ig-bioscience")
  );
}

/**
 * Helper to fetch all project slugs for static path generation
 */
export function getAllProjectSlugs(): string[] {
  return projects.map((p) => p.slug);
}

/**
 * Helper to retrieve adjacent projects for next/previous navigation
 */
export function getAdjacentProjects(currentSlug: string): {
  prev: Project;
  next: Project;
} {
  const index = projects.findIndex(
    (p) =>
      p.slug === currentSlug ||
      (currentSlug === "magicbox" && p.slug === "magicbox-mglink") ||
      (currentSlug === "igbioscience" && p.slug === "ig-bioscience")
  );

  const safeIndex = index === -1 ? 0 : index;
  const prevIndex = (safeIndex - 1 + projects.length) % projects.length;
  const nextIndex = (safeIndex + 1) % projects.length;

  return {
    prev: projects[prevIndex],
    next: projects[nextIndex],
  };
}